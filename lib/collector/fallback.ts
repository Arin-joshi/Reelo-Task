export function fallbackFor(source: ListingSource): ListingWrite {
  const row = FALLBACK_BY_ID[source.airbnbId];
  if (row) {
    return {
      ...row,
      collected_at: new Date().toISOString(),
    };
  }

  return {
    airbnb_id: source.airbnbId,
    name: "Airbnb listing",
    price: null,
    currency: "USD",
    location: "Unknown",
    rating: null,
    review_count: null,
    image_url: photo("photo-1502672260266-1c1ef2d93688"),
    listing_url: source.url,
    category: source.category,
    is_guest_favorite: false,
    collected_at: new Date().toISOString(),
  };
}
